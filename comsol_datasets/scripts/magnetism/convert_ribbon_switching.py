"""Step 7 COMSOL data: rotation / nucleation runs (field from t = 0) and wall runs (wall = 2: wall nucleated at the
left end, relaxed at H = 0 until trel, then the field). Usage: python convert_ribbon_switching.py <out_dir> <log> [<log> ...]
(logs of the batch classes generated by gen_ribbon.py from ribbon_cases_switching.json)."""
import sys, csv, numpy as np
from parse_ribbon import load
OUT = sys.argv[1] if len(sys.argv) > 1 else '../../data/magnetism'
rows, npz = [], {}
for fn in sys.argv[2:]:
    D = load(fn)
    for cid, c in D['cases'].items():
        seeded = c[-2] == '2'
        t_on = float(c[-1]) if seeded else 0.0
        if (cid, 'PR') not in D or (cid, 'MX') not in D or cid not in D.get('time', {}):
            rows.append([cid, '', c[3], c[4], c[6], c[1], t_on, '', '', '', '', '', 'failed']); continue
        av = np.array(D[(cid, 'AV')]); t = av[:, 0]
        mxi = av[:, 4] * 300 / 240                      # average of m_x over the iron part 30-270 nm
        kind = 'wall' if seeded else ('nucleation' if float(c[4]) > 0 else 'rotation')
        on = t >= t_on - 1e-9
        tt, mm = t[on], mxi[on]
        up = np.where((mm[:-1] < 0) & (mm[1:] >= 0))[0]
        tsw = (tt[up[0]] + (tt[up[0] + 1] - tt[up[0]]) * (-mm[up[0]]) / (mm[up[0] + 1] - mm[up[0]]) - t_on) if len(up) else np.nan
        mx = np.array(D[(cid, 'MX')])
        mxerr = mx[mx[:, 0] >= 0.5, 1].max()           # |m| error after the first 0.5 ns (the seed start is abrupt)
        rows.append([cid, kind, float(c[3]), float(c[4]), float(c[6]), float(c[1]), t_on, mm[0], mxi[-1],
                     int(mxi[-1] > 0), tsw, mxerr, D['time'][cid]])
        npz[cid + '_t_ns'] = t.astype(np.float32); npz[cid + '_mx_iron'] = mxi.astype(np.float32)
        if cid.startswith('e0') or cid.startswith('h1') or cid.startswith('n'):   # profiles of the reference iron
            pr = np.array(D[(cid, 'PR')], dtype=np.float32); n = (pr.shape[1] - 1) // 3
            npz[cid + '_m'] = np.stack([pr[:, 1:1 + n], pr[:, 1 + n:1 + 2 * n], pr[:, 1 + 2 * n:]], -1)
npz['x_nm'] = np.arange(0, 301, 2.0).astype(np.float32)
np.savez_compressed(f'{OUT}/ribbon_switching_comsol.npz', **npz)
with open(f'{OUT}/ribbon_switching_comsol.csv', 'w', newline='') as fh:
    w = csv.writer(fh)
    w.writerow(['case_id', 'mechanism', 'HK_A_per_m', 'pinning_eps', 'end_HK_factor', 'H_A_per_m', 't_field_on_ns',
                'mx_iron_start', 'mx_iron_end', 'switched', 't_switch_ns', 'max_norm_error', 'solve_time_s'])
    for r in rows:
        w.writerow([r[0], r[1]] + [f'{v:.6g}' if isinstance(v, float) else v for v in r[2:]])
for r in rows:
    print(r[0], r[1], r[2], r[3], r[5], 'on %.0f start %.2f end %.2f sw %s t %.2f err %.1e' % tuple(r[6:12]) if r[1] else r)
